// Copies the AgentBudget ABI out of the Foundry build so the TS side never
// hand-maintains it. Emits a TS module with `as const` so viem can infer
// event/error types. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
const artifact = JSON.parse(readFileSync("contracts/out/AgentBudget.sol/AgentBudget.json", "utf8"));
const src = `// generated by scripts/extract-abi.mjs — do not edit\nexport const vaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
writeFileSync("shared/AgentBudget.abi.ts", src);
console.log("wrote shared/AgentBudget.abi.ts");
